// Адреса, которым можно доверить атрибут href.
//
// Ссылка на задачу берётся из данных комнаты, а описание задачи — из Jira; и то,
// и другое приходит со стороны. Адрес вида `javascript:…` в href — это код,
// который выполнится по клику в чужой вкладке, а `data:text/html,…` — чужая
// страница на нашем домене. Экранирование HTML от этого не спасает: оно чинит
// разметку, а не схему адреса.

// Разрешаем только то, что действительно ведёт наружу или внутрь сайта.
const SAFE_SCHEMES = ['http:', 'https:', 'mailto:'];

function safeUrl(raw) {
    // Управляющие символы выбрасываем первым делом: браузер делает то же самое,
    // и «java\tscript:alert(1)» для него — обычный javascript:. Проверка схемы
    // по исходной строке такую запись пропускала как относительный путь.
    const адрес = String(raw == null ? '' : raw).replace(/[\u0000-\u001F\u007F]/g, '').trim();
    if (!адрес) return '#';

    // Относительные адреса схемы не имеют и потому безопасны: они остаются на
    // нашем домене. «//host/path» — это тоже http(s), браузер подставит схему.
    if (адрес.startsWith('/') || адрес.startsWith('#') || безСхемы(адрес)) return адрес;

    try {
        // Схему разбирает сам браузер: он же потом и будет её исполнять, и всякие
        // «java\tscript:» или «JaVaScRiPt:» разбирает так же, как в href
        const разобранный = new URL(адрес, 'https://example.invalid');
        return SAFE_SCHEMES.includes(разобранный.protocol) ? адрес : '#';
    } catch {
        return '#';
    }
}

// Есть ли вообще схема: «PP-1/browse» — не адрес со схемой, а относительный путь
function безСхемы(адрес) {
    return !/^[a-zA-Z][a-zA-Z0-9+.-]*:/.test(адрес) && !адрес.startsWith('//');
}

if (typeof module !== 'undefined' && module.exports) {
    module.exports = { safeUrl, SAFE_SCHEMES };
}
